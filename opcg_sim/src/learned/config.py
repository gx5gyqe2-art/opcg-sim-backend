# 箱の内部解決の深さ（v39・2026-08-06）: `resolved_branch_values` が枝の**残りの窓**を進めるとき、
# 何段まで「出口 value 最良」で読むか（0=従来＝policy 最良手／1=次の窓まで実対局と同一規約）。
